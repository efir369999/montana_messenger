export let locale = navigator.language || "en";
let ru = locale.toLowerCase().startsWith("ru");
export function setLanguage(code) {
  if (code === "en" || code === "ru") { locale = code; ru = code === "ru"; }
}

/** A size as iOS speaks it (mtSize: .byteCount(style: .file) in the app's language, by the same ICU): units of 1000 -- of 1024 when
 *  binary (MontanaNetworkView.mtBytes) --, bytes by their full name, kB whole, MB to one place, GB and up to two, a zero spelled out. */
export function mtSize(bytes, binary = false) {
  const b = Math.max(0, Number(bytes) || 0), k = binary ? 1024 : 1000;
  const units = ["byte", "kilobyte", "megabyte", "gigabyte", "terabyte", "petabyte"];
  const say = (i, v) => new Intl.NumberFormat(locale, { style: "unit", unit: units[i], unitDisplay: i ? "short" : "long", maximumFractionDigits: [0, 0, 1, 2, 2, 2][i] }).format(v);
  if (!b) return say(1, 0).replace("0", ru ? "Ноль" : "Zero");
  let i = 0;
  while (i < units.length - 1 && b >= k ** (i + 1)) i++;
  const v = b / k ** i, s = say(i, v);
  // 999 999 bytes round to "1000 kB"; the platform says "1 MB"
  return i < units.length - 1 && Math.round(v * 10 ** [0, 0, 1, 2, 2, 2][i]) >= k * 10 ** [0, 0, 1, 2, 2, 2][i] ? say(i + 1, v / k) : s;
}

/** The day's word (iOS MTDayLabel.of): «Today», «Yesterday», else the day and the month («19 октября»). */
export function dayWord(ms) {
  const d = new Date(ms), now = new Date();
  const day = new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime();
  if (day === today) return t("Today");
  if (day === today - 86400000) return t("Yesterday");
  return d.toLocaleDateString(locale, { day: "numeric", month: "long" });
}

