def paths(xml_path):
    root = ET.parse(xml_path).getroot()
    box = [float(root.get(A + "viewportWidth")), float(root.get(A + "viewportHeight"))]
    out = []
    for p in root.iter("path"):
        stroke = p.get(A + "strokeColor")
        fill = p.get(A + "fillColor")
        out.append({
            "d": p.get(A + "pathData"),
            "fill": "none" if (fill in (None, "#00000000")) else "currentColor",
            "stroke": "currentColor" if stroke else "none",
            "strokeWidth": float(p.get(A + "strokeWidth", "0")),
            "cap": p.get(A + "strokeLineCap", "butt"),
            "join": p.get(A + "strokeLineJoin", "miter"),
            "evenodd": p.get(A + "fillType") == "evenOdd",
        })
    return box, out


